"""Write every distinct prompt variant for one scenario per wording to docs/prompt_review.md (Checkpoint 1)."""
from pathlib import Path

from . import config as C, scenarios as S
from .run import arithmetic_items

CELLS = ["partner_D_q80_F20", "audit_D_q80_F20", "partner_U_q80_F20", "neutral_U_F20", "partner_D_q10_F0", "authorized_offer_positive_control"]


def main():
    sc = S.scenarios("main")
    out = ["# Prompt review (Checkpoint 1)\n", "Generated by `python -m betrayal.review` from `prompts/templates.toml`.\n",
           f"## System prompt\n\n```\n{S.T['system']}\n```\n"]
    for w in (1, 2):
        s = next(x for x in sc if x["w"] == w)
        for cid in CELLS if w == 1 else CELLS[:4]:
            out.append(f"## Wording {w}, cell `{cid}`\n\n```\n{S.render(s, C.CELL[cid])[1]['content']}\n```\n")
    s = sc[0]
    for k in ("diagnostic", "diagnostic_work"):
        d = S.render(s, C.CELL["partner_U_q80_F20"], k)[1]["content"]
        out.append(f"## Diagnostic fork `{k}` (replaces the DECISION section)\n\n```\n{d[d.index('QUESTIONS'):]}\n```\n")
    out.append("## Arithmetic / comprehension control\n")
    for iid, msgs, ans in arithmetic_items():
        out.append(f"- `{iid}` (correct: {ans:g}): {msgs[1]['content'].splitlines()[0]}")
    a = S.T["arithmetic"]
    out.append(f"\nAnswer-only format: `{a['format']}`  \nWith-working format: `{a['format_work']}`")
    Path(Path(__file__).parent.parent / "docs").mkdir(exist_ok=True)
    (Path(__file__).parent.parent / "docs" / "prompt_review.md").write_text("\n".join(out) + "\n")


if __name__ == "__main__" and __import__("sys").argv[1:] != ["s2"]:
    main()


def main_s2(F=60):
    """docs/prompt_review_s2.md: one full Study-2 prompt, then the varying bullet for every cell, both wordings."""
    sc = S.scenarios("main2")
    out = ["# Study 2 prompt review (Checkpoint A)\n",
           f"Generated by `python -m betrayal.review s2` from `prompts/templates.toml` [record]. Penalty shown as F={F} "
           "(the pilot chooses F per model and risk level). Everything outside the exposure bullets is identical to Study 1.\n"]
    s1 = next(x for x in sc if x["w"] == 1)
    out.append(f"## Full prompt: wording 1, cell `S10`\n\n```\n{S.render_s2(s1, C.S2_CELL['S10'], F)[1]['content']}\n```\n")
    for w in (1, 2):
        s = next(x for x in sc if x["w"] == w)
        for c in C.S2_CELLS:
            body = S.render_s2(s, c, F)[1]["content"]
            bullets = body.split("probability 80%.\n", 1)[1].split("\n- If you do not send")[0]
            out.append(f"## Wording {w}, cell `{c.id}` (exposure bullets only)\n\n```\n{bullets}\n```\n")
    d = S.render_s2(s1, C.S2_CELL["R1"], F, "diagnostic_work")[1]["content"]
    out.append(f"## Diagnostic fork (with working), cell `R1`\n\n```\n{d[d.index('QUESTIONS'):]}\n```\n")
    (Path(__file__).parent.parent / "docs" / "prompt_review_s2.md").write_text("\n".join(out) + "\n")



def main_s3(model="deepseek/deepseek-v3.2"):
    """docs/prompt_review_s3.md: full Study-3a prompts (both wordings), then what each other cell changes."""
    import difflib
    sc = S.scenarios("main3")
    out = ["# Study 3a prompt review (Checkpoint A3)\n",
           f"Generated by `python -m betrayal.review s3` from `prompts/templates.toml` [s3], shown for {model} "
           f"(F = {C.S3_F[model]}, EV-matched override penalty F_s = {C.s3_fs(model, C.S3_CELL['M3_E'])}). "
           "Option order rotates over all 6 orders per scenario; the MESSAGE block is the Study-2 partner block "
           "except that a report now blocks the bonus.\n"]
    for w in (1, 2):
        s = next(x for x in sc if x["w"] == w)
        out.append(f"## Full prompt: wording {w}, cell `M3_E`\n\n```\n{S.render_s3(s, C.S3_CELL['M3_E'], model)[0][1]['content']}\n```\n")
    s = next(x for x in sc if x["w"] == 1)
    base = S.render_s3(s, C.S3_CELL["M3_E"], model)[0][1]["content"].splitlines()
    for c in C.S3_CELLS[1:]:
        d = [l for l in difflib.unified_diff(base, S.render_s3(s, c, model)[0][1]["content"].splitlines(), lineterm="", n=0)
             if l[:1] in "+-" and l[:3] not in ("+++", "---")]
        out.append(f"## `{c.id}`: lines changed vs `M3_E` (wording 1)\n\n```diff\n" + "\n".join(d) + "\n```\n")
    (Path(__file__).parent.parent / "docs" / "prompt_review_s3.md").write_text("\n".join(out) + "\n")



def main_s3b(F=40):
    """docs/prompt_review_s3b.md: A's prompt (E), the other cells' history lines, monitor and judge prompts, instruments."""
    import json
    from . import verifier as V
    root = Path(__file__).parent.parent
    hist = {h["scenario_id"]: h for h in map(json.loads, (root / "data" / "pilot3b" / "history.jsonl").open())}
    s = S.scenarios("pilot3b")[0]
    h = hist[s["id"]]
    body = {c.id: S.render_s3b(s, c, F, h)[1]["content"] for c in C.S3B_CELLS}
    ins = V.instruments()
    out = ["# Study 3b prompt review (Checkpoint A3b)\n",
           f"Generated by `python -m betrayal.review s3b`. F={F} shown (chosen on pilot E). Monitor: {ins['monitor']}; "
           f"judge: {ins['judge']}; second monitor: {ins['second_monitor']}; recency history k={ins['k_recency']} flags. "
           "History outcomes are real monitor outcomes on other agents' messages, drawn as in settlement.\n",
           f"## Agent A, cell `E`\n\n```\n{body['E']}\n```\n"]
    for c in ("L", "LOW", "HIGH"):
        out.append(f"## Cell `{c}`: history lines\n\n```\n" + "\n".join(x for x in body[c].splitlines() if x.strip().startswith("Message")) + "\n```\n")
    aut = [x for x in body["AUTH_E"].splitlines() if "authorized" in x or "flag has no" in x]
    out.append("## `AUTH_E` (collateral check): changed lines\n\n```\n" + "\n".join(aut) + "\n```\n")
    m = V.mon_messages(s, "<draft>")
    out += [f"## Monitor prompt\n\n```\n[system] {m[0]['content']}\n\n{m[1]['content']}\n```\n",
            f"## Hardened monitor adds\n\n```\n{S.T['s3b']['mon_hardened']}\n```\n",
            f"## Judge prompt (partner perspective)\n\n```\n{V.judge_messages(s, '<draft>')[0]['content']}\n```\n",
            "## Instrument gates (pool, before any agent-A data)\n\n```json\n" +
            json.dumps({m: {k: v for k, v in r.items()} for m, r in ins["candidates"].items()}, indent=1, default=float) + "\n```\n"]
    (root / "docs" / "prompt_review_s3b.md").write_text("\n".join(out) + "\n")


if __name__ == "__main__" and __import__("sys").argv[1:] == ["s3b"]:
    main_s3b()
if __name__ == "__main__" and __import__("sys").argv[1:] == ["s2"]:
    main_s2()
if __name__ == "__main__" and __import__("sys").argv[1:] == ["s3"]:
    main_s3()
